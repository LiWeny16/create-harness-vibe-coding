// Adapter contract (same as markdown-node): handler(nodeId, projectRoot, payload).
export function write(nodeId, projectRoot, payload = {}) {
  const { html, expectedRevision, lockId, lockOwner } = payload
  const current = requireDisplayNode(getComponentNode(projectRoot, nodeId))
  const lock = isLocked(current.node.nodeId, undefined, { projectRoot })
  if (lock) {
    const declaredLockId = lockId !== undefined && lockId !== null ? String(lockId).trim() : ''
    const declaredOwner = String(lockOwner || '').trim()
    const holdsLock = (declaredLockId !== '' && declaredLockId === lock.lockId)
      || (declaredLockId === '' && declaredOwner !== '' && declaredOwner === lock.holder)
    if (!holdsLock) {
      const error = new ComponentNodeError(
        `Display node is locked by ${lock.holder}. Reread, merge your changes, and retry.`,
        { statusCode: 409, code: 'display_locked' },
      )
      error.currentRevision = current.node.revision
      error.expectedRevision = expectedRevision === undefined || expectedRevision === null
        ? current.node.revision
        : expectedRevision
      throw error
    }
  }
  if (expectedRevision !== undefined && expectedRevision !== null) {
    const conflict = assertRevision(current.node.revision, expectedRevision)
    if (conflict) throw conflict
  }
  const filePath = reportHtmlPath(projectRoot, current.node.nodeId)
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, String(html ?? ''), 'utf8')
  const bytes = Buffer.byteLength(html || '', 'utf8')
  const updated = updateComponentNode(projectRoot, current.node.nodeId, {
    revision: current.node.revision,
    html: { bytes, updatedAt: new Date().toISOString() },
  })
  return { ok: true, bytes, revision: updated.node.revision }
}

export function read(nodeId, projectRoot, payload = {}) {
  const current = requireDisplayNode(getComponentNode(projectRoot, nodeId))
  const filePath = reportHtmlPath(projectRoot, current.node.nodeId)
  const html = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : ''
  return { ok: true, html, revision: current.node.revision, usage: DISPLAY_USAGE }
}

// Serves the report HTML with excalidraw placeholders expanded to inline SVG.
// Falls back to the themed default template until an agent writes content.
export function renderHtml(projectRoot, { nodeId }) {
  const current = requireDisplayNode(getComponentNode(projectRoot, nodeId))
  const filePath = reportHtmlPath(projectRoot, current.node.nodeId)
  const title = current.node.title || 'Report'
  const html = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : defaultDisplayTemplate({ title })
  return expandExcalidrawPlaceholders(projectRoot, html)
}

function expandExcalidrawPlaceholders(projectRoot, html) {
  return String(html || '').replace(EXCALIDRAW_PLACEHOLDER, (match, refNodeId) => {
    try {
      const ref = getComponentNode(projectRoot, refNodeId)
      if (ref.state.type !== 'excalidraw') return match
      const elements = Array.isArray(ref.state.scene?.elements) ? ref.state.scene.elements : []
      const svg = renderSceneSvg(elements)
      return `<figure class="harness-excalidraw">${svg}<figcaption>Excalidraw scene · <a href="#open-node:${refNodeId}">open interactive node</a></figcaption></figure>`
    } catch {
      return match // unresolvable reference: keep the placeholder text
    }
  })
}
