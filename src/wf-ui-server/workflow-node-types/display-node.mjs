// display-node.mjs
//
// Display node adapter: agents write full HTML reports to a display node; the
// user views them on the canvas (fullscreen iframe). The HTML is a REAL file
// on disk (Harness/a2a/component-nodes/<nodeId>/report.html) with FULLY OPEN
// JS — per user decision the report content carries the same trust as the
// agent's own terminal (local tool, no auth; agents are the user's own).
// {{excalidraw:<nodeId>}} placeholders expand to self-contained inline SVGs at
// serve time, so diagrams embed without CDN or runtime JS.

import fs from 'node:fs'
import path from 'node:path'
import { nodeStoreRoot } from '../node-store-utils.mjs'
import {
  ComponentNodeError,
  assertRevision,
  getComponentNode,
  isLocked,
  updateComponentNode,
} from '../component-node-store.mjs'
import { renderSceneSvg } from '../excalidraw-svg.mjs'

export const DISPLAY_USAGE = [
  'Writing/modifying HTML files is normal work and always allowed.',
  'When PRESENTING a report or results to the user: if the user has not explicitly named a target file, the default presentation surface is a Display node — write a self-contained HTML document with display.write.',
  'The user opens Display nodes on the canvas (fullscreen). Never open a browser yourself.',
  'Theme: white background, blue (#2563EB)/black text, Claude-yellow (#D97757) accents; semantic classes: .report-title, .report-section, .card, .metric, .highlight, .muted.',
  'Diagrams: embed an Excalidraw node scene with the placeholder {{excalidraw:<nodeId>}} anywhere in the HTML.',
].join(' ')

const EXCALIDRAW_PLACEHOLDER = /\{\{excalidraw:([A-Za-z0-9-]+)\}\}/g

export function reportHtmlPath(projectRoot, nodeId) {
  return path.join(nodeStoreRoot(projectRoot, 'component-nodes'), nodeId, 'report.html')
}

function requireDisplayNode(current) {
  if (current.state.type !== 'display') {
    throw new ComponentNodeError(`Node is not a display node: ${current.node.nodeId}`, {
      statusCode: 409,
      code: 'TYPE_MISMATCH',
    })
  }
  return current
}

